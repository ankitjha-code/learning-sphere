import { z } from 'zod';
import { and, desc, eq, isNull, sql } from 'drizzle-orm';
import { db } from '../../db/client';
import { reports, users, threads, posts, resources, aiMessages, jobPostings, sessions } from '../../db/schema';
import { type AppEnv, requirePlatformAdmin } from '../../lib/context';
import { body, idParam, query } from '../../lib/validate';
import { badRequest, conflict, notFound } from '../../lib/errors';
import { audit } from '../../lib/audit';
import { notify } from '../../lib/notify';
import { offsetOf, pageParams } from './common';

/** Mounted at /api/admin/reports. Content moderation queue across every reportable target. Platform admins only. */
export const adminModerationRoutes = new Hono<AppEnv>();

const TARGET_TYPES = ['post', 'thread', 'user', 'resource', 'ai_message', 'job_posting'] as const;
const QUICK_ACTIONS = ['hide_post', 'hide_thread', 'unpublish_resource', 'suspend_user', 'close_job_posting'] as const;
type QuickAction = (typeof QUICK_ACTIONS)[number];

const QUICK_ACTION_FOR: Record<string, QuickAction[]> = {
  post: ['hide_post'],
  thread: ['hide_thread'],
  resource: ['unpublish_resource'],
  user: ['suspend_user'],
  job_posting: ['close_job_posting'],
  ai_message: [],
};

const QUICK_ACTION_LABEL: Record<QuickAction, string> = {
  hide_post: 'Hide this reply',
  hide_thread: 'Hide this thread',
  unpublish_resource: 'Unpublish (archive) this resource',
  suspend_user: 'Suspend this user',
  close_job_posting: 'Close this job posting',
};

const isUuid = (v: string) => /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i.test(v);
const excerpt = (s: string | null | undefined, n = 400) => (s ? (s.length > n ? s.slice(0, n) + '...' : s) : null);

function safeHost(url: string | null) {
  if (!url) return null;
  try {
    return new URL(url).hostname;
  } catch {
    return null;
  }
}

export type TargetPreview = {
  exists: boolean;
  title: string | null;
  excerpt: string | null;
  status: string | null;
  authorId: string | null;
  authorName: string | null;
  context: string | null;
};

async function authorName(id: string | null) {
  if (!id) return null;
  const [u] = await db.select({ name: users.name }).from(users).where(eq(users.id, id));
  return u?.name ?? null;
}

/** Safe, truncated preview of reported content. Never returns secrets or full private conversations. */
export async function targetPreview(type: string, id: string): Promise<TargetPreview> {
  const none: TargetPreview = { exists: false, title: null, excerpt: null, status: null, authorId: null, authorName: null, context: null };
  if (!isUuid(id)) return none;
  if (type === 'thread') {
    const [t] = await db.select({ title: threads.title, body: threads.body, status: threads.status, authorId: threads.authorId }).from(threads).where(eq(threads.id, id));
    return t ? { exists: true, title: t.title, excerpt: excerpt(t.body), status: t.status, authorId: t.authorId, authorName: await authorName(t.authorId), context: 'Community thread' } : none;
  }
  if (type === 'post') {
    const [p] = await db
      .select({ body: posts.body, status: posts.status, authorId: posts.authorId, threadTitle: threads.title })
      .from(posts)
      .innerJoin(threads, eq(threads.id, posts.threadId))
      .where(eq(posts.id, id));
    return p ? { exists: true, title: `Reply in "${p.threadTitle}"`, excerpt: excerpt(p.body), status: p.status, authorId: p.authorId, authorName: await authorName(p.authorId), context: 'Community reply' } : none;
  }
  if (type === 'resource') {
    const [r] = await db.select({ title: resources.title, summary: resources.summary, status: resources.status, authorId: resources.authorId, url: resources.url }).from(resources).where(eq(resources.id, id));
    return r ? { exists: true, title: r.title, excerpt: excerpt(r.summary), status: r.status, authorId: r.authorId, authorName: await authorName(r.authorId), context: safeHost(r.url) ? `Library resource linking to ${safeHost(r.url)}` : 'Library resource' } : none;
  }
  if (type === 'user') {
    const [u] = await db.select({ name: users.name, status: users.status, platformRole: users.platformRole }).from(users).where(eq(users.id, id));
    return u ? { exists: true, title: u.name, excerpt: null, status: u.status, authorId: id, authorName: u.name, context: u.platformRole ? 'Platform staff account' : 'User account' } : none;
  }
  if (type === 'ai_message') {
    const [m] = await db.select({ content: aiMessages.content, role: aiMessages.role, provider: aiMessages.provider }).from(aiMessages).where(eq(aiMessages.id, id));
    return m ? { exists: true, title: m.role === 'assistant' ? 'AI assistant reply' : 'Message in an AI conversation', excerpt: excerpt(m.content, 600), status: null, authorId: null, authorName: null, context: m.provider ? `Generated by ${m.provider}` : null } : none;
  }
  if (type === 'job_posting') {
    const [j] = await db.select({ title: jobPostings.title, description: jobPostings.description, status: jobPostings.status, createdBy: jobPostings.createdBy }).from(jobPostings).where(eq(jobPostings.id, id));
    return j ? { exists: true, title: j.title, excerpt: excerpt(j.description), status: j.status, authorId: j.createdBy, authorName: await authorName(j.createdBy), context: 'Job posting' } : none;
  }
  return none;
}

adminModerationRoutes.get('/', async (c) => {
  requirePlatformAdmin(c);
  const q = query(
    c,
    z.object({ ...pageParams, status: z.enum(['open', 'actioned', 'dismissed', 'all']).default('open'), targetType: z.enum(TARGET_TYPES).optional() }),
  );
  const where = and(q.status !== 'all' ? eq(reports.status, q.status) : undefined, q.targetType ? eq(reports.targetType, q.targetType) : undefined);
  const [{ total }] = await db.select({ total: sql<number>`count(*)::int` }).from(reports).where(where);
  const rows = await db
    .select({ r: reports, reporterName: users.name })
    .from(reports)
    .leftJoin(users, eq(users.id, reports.reporterId))
    .where(where)
    .orderBy(desc(reports.createdAt))
    .limit(q.pageSize)
    .offset(offsetOf(q));
  const items = [];
  for (const { r, reporterName } of rows) {
    const p = await targetPreview(r.targetType, r.targetId);
    const [{ sameTarget }] = await db
      .select({ sameTarget: sql<number>`count(*)::int` })
      .from(reports)
      .where(and(eq(reports.targetType, r.targetType), eq(reports.targetId, r.targetId), eq(reports.status, 'open')));
    items.push({ ...r, reporterName, targetTitle: p.title, targetExists: p.exists, targetStatus: p.status, openReportsOnTarget: sameTarget });
  }
  const counts = await db.select({ status: reports.status, n: sql<number>`count(*)::int` }).from(reports).groupBy(reports.status);
  return c.json({ items, total, page: q.page, pageSize: q.pageSize, counts: Object.fromEntries(counts.map((x) => [x.status, x.n])) });
});

adminModerationRoutes.get('/:id', async (c) => {
  requirePlatformAdmin(c);
  const id = idParam(c);
  const [row] = await db.select({ r: reports, reporterName: users.name }).from(reports).leftJoin(users, eq(users.id, reports.reporterId)).where(eq(reports.id, id));
  if (!row) throw notFound('Report');
  const preview = await targetPreview(row.r.targetType, row.r.targetId);
  const others = await db
    .select({ id: reports.id, reason: reports.reason, details: reports.details, status: reports.status, createdAt: reports.createdAt })
    .from(reports)
    .where(and(eq(reports.targetType, row.r.targetType), eq(reports.targetId, row.r.targetId), sql`${reports.id} <> ${id}`))
    .orderBy(desc(reports.createdAt))
    .limit(20);
  const available = preview.exists ? QUICK_ACTION_FOR[row.r.targetType] ?? [] : [];
  return c.json({
    report: { ...row.r, reporterName: row.reporterName },
    preview,
    otherReports: others,
    quickActions: available.map((a) => ({ id: a, label: QUICK_ACTION_LABEL[a] })),
  });
});

async function applyQuickAction(c: Parameters<typeof requirePlatformAdmin>[0], action: QuickAction, targetType: string, targetId: string) {
  if (!(QUICK_ACTION_FOR[targetType] ?? []).includes(action)) throw badRequest(`"${QUICK_ACTION_LABEL[action]}" does not apply to a ${targetType.replace('_', ' ')}.`);
  if (action === 'hide_post') await db.update(posts).set({ status: 'hidden' }).where(eq(posts.id, targetId));
  if (action === 'hide_thread') await db.update(threads).set({ status: 'hidden' }).where(eq(threads.id, targetId));
  if (action === 'unpublish_resource') await db.update(resources).set({ status: 'archived', updatedAt: new Date() }).where(eq(resources.id, targetId));
  if (action === 'close_job_posting') await db.update(jobPostings).set({ status: 'closed', updatedAt: new Date() }).where(eq(jobPostings.id, targetId));
  if (action === 'suspend_user') {
    const auth = requirePlatformAdmin(c);
    const [u] = await db.select({ status: users.status, platformRole: users.platformRole }).from(users).where(eq(users.id, targetId));
    if (!u) throw notFound('User');
    if (targetId === auth.user.id) throw conflict('You cannot suspend your own account.');
    if (u.platformRole) throw conflict('Platform staff accounts cannot be suspended from the moderation queue. Use Admin, Users.');
    if (u.status === 'active' || u.status === 'pending_deletion') {
      await db.update(users).set({ status: 'suspended', updatedAt: new Date() }).where(eq(users.id, targetId));
      await db.update(sessions).set({ revokedAt: new Date() }).where(and(eq(sessions.userId, targetId), isNull(sessions.revokedAt)));
      await audit(c, { action: 'admin.user_suspended', targetType: 'user', targetId, meta: { reason: 'Moderation report', via: 'moderation' } });
    }
  }
}

adminModerationRoutes.post('/:id/resolve', async (c) => {
  const auth = requirePlatformAdmin(c);
  const id = idParam(c);
  const input = await body(
    c,
    z.object({
      outcome: z.enum(['dismissed', 'actioned']),
      resolution: z.string().trim().min(3, 'Add a short note explaining the decision.').max(1000),
      quickAction: z.enum(QUICK_ACTIONS).optional(),
      includeSameTarget: z.boolean().default(true),
    }),
  );
  const [r] = await db.select().from(reports).where(eq(reports.id, id));
  if (!r) throw notFound('Report');
  if (r.status !== 'open') throw conflict('This report was already resolved.');
  if (input.quickAction && input.outcome !== 'actioned') throw badRequest('A quick action can only be used when marking the report as actioned.');
  if (input.quickAction) await applyQuickAction(c, input.quickAction, r.targetType, r.targetId);

  const resolved = await db
    .update(reports)
    .set({ status: input.outcome, resolution: input.resolution, resolvedBy: auth.user.id, resolvedAt: new Date() })
    .where(
      and(
        eq(reports.status, 'open'),
        input.includeSameTarget ? and(eq(reports.targetType, r.targetType), eq(reports.targetId, r.targetId)) : eq(reports.id, id),
      ),
    )
    .returning({ id: reports.id, reporterId: reports.reporterId });
  await audit(c, {
    action: 'admin.report_resolved',
    orgId: r.orgId,
    targetType: r.targetType,
    targetId: r.targetId,
    meta: { reportId: id, outcome: input.outcome, quickAction: input.quickAction ?? null, resolvedCount: resolved.length, resolution: input.resolution },
  });
  // Reporters learn the outcome in general terms only (no details about other users).
  for (const reporterId of new Set(resolved.map((x) => x.reporterId))) {
    await notify(reporterId, {
      type: 'moderation.report_reviewed',
      category: 'general',
      title: 'Your report was reviewed',
      body: input.outcome === 'actioned' ? 'Thank you. A moderator reviewed your report and took action.' : 'Thank you. A moderator reviewed your report and did not find a rule violation.',
      email: false,
    });
  }
  return c.json({ ok: true, resolved: resolved.length });
});
