/** Plans with admin edits applied (stored in system_settings 'plans' as a map id -> plan). */
export async function getPlans(): Promise<Plan[]> {
  const stored = await readSetting<Record<string, unknown>>('plans', {});
  return DEFAULT_PLANS.map((d) => {
    const s = stored?.[d.id];
    if (!s || typeof s !== 'object') return d;
    const merged = {
      ...d,
      ...(s as object),
      id: d.id,
      limits: { ...d.limits, ...((s as { limits?: object }).limits ?? {}) },
      entitlements: { ...d.entitlements, ...((s as { entitlements?: object }).entitlements ?? {}) },
    };
    const parsed = planSchema.safeParse(merged);
    return parsed.success ? parsed.data : d;
  });
}

export async function getPlan(id: string | null | undefined): Promise<Plan> {
  const plans = await getPlans();
  return plans.find((p) => p.id === id) ?? plans[0];
}

// ---------- Entitlements ----------

export type Entitlements = {
  /** 'demonstration' unless a payment provider is configured (see server/modules/billing). */
  mode: BillingMode;
  notice: string;
  plan: { id: PlanId; name: string; description: string };
  planSource: 'organization' | 'personal';
  orgId: string | null;
  limits: PlanLimits & { orgAiMonthlyRequestLimit: number | null; maxUploadMb: number };
  entitlements: Record<Entitlement, boolean>;
  features: Record<FeatureFlag, boolean>;
  explanations: string[];
};

/**
 * What a user may do in the context of an organization (or personally when orgId is null).
 * Combines: the org's plan, the org's policies, and platform feature flags (a flag that
 * is off disables the feature for everyone regardless of plan).
 */
export async function getEntitlements(orgId: string | null, _userId: string): Promise<Entitlements> {
  let planId: string = 'free';
  let policies = readOrgPolicies(null);
  if (orgId) {
    const [o] = await db.select({ planId: organizations.planId, settings: organizations.settings }).from(organizations).where(eq(organizations.id, orgId));
    if (o) {
      planId = o.planId;
      policies = readOrgPolicies(o.settings);
    }
  }
  const plan = await getPlan(planId);
  const flags = await getFeatureFlags();
  const quotaBytes = await getUserStorageQuotaBytes();
  const storagePerUserMb = Math.min(plan.limits.storagePerUserMb, Math.round(quotaBytes / (1024 * 1024)));
  const ent = { ...plan.entitlements };
  const explanations: string[] = [`${plan.name} plan${orgId ? ' of this organization' : ' (personal default)'}.`];
  if (!flags.ai || (orgId && !policies.aiEnabled)) {
    ent.aiAssistants = false;
    explanations.push(!flags.ai ? 'AI assistants are turned off by the platform administrator.' : 'AI assistants are turned off by your organization policy.');
  }
  if (storagePerUserMb < plan.limits.storagePerUserMb) explanations.push(`Storage is capped at the platform quota of ${storagePerUserMb} MB per user.`);
  const billing = billingMode();
  return {
    mode: billing.mode,
    notice: billing.notice,
    plan: { id: plan.id, name: plan.name, description: plan.description },
    planSource: orgId ? 'organization' : 'personal',
    orgId,
    limits: { ...plan.limits, storagePerUserMb, orgAiMonthlyRequestLimit: policies.aiMonthlyRequestLimit, maxUploadMb: policies.maxUploadMb },
    entitlements: ent,
    features: flags,
    explanations,
  };
}

// ---------- Limits ----------

export type LimitMetric = 'ai.requests.day' | 'ai.requests.month' | 'org.members' | 'storage.bytes' | 'job_postings.active' | 'assessments.month';

export type LimitCheck = {
  metric: LimitMetric;
  scope: 'user' | 'org';
  used: number;
  limit: number | null;
  allowed: boolean;
  period: string | null;
  explanation: string;
};

const startOfUtcDay = () => {
  const d = new Date();
  return new Date(Date.UTC(d.getUTCFullYear(), d.getUTCMonth(), d.getUTCDate()));
};
const startOfUtcMonth = () => {
  const d = new Date();
  return new Date(Date.UTC(d.getUTCFullYear(), d.getUTCMonth(), 1));
};

async function bestPlanForUser(userId: string): Promise<Plan> {
  const rows = await db
    .select({ planId: organizations.planId })
    .from(memberships)
    .innerJoin(organizations, eq(organizations.id, memberships.orgId))
    .where(and(eq(memberships.userId, userId), eq(memberships.status, 'active'), eq(organizations.status, 'active')));
  const plans = await getPlans();
  const candidates = [plans[0], ...rows.map((r) => plans.find((p) => p.id === r.planId)).filter((p): p is Plan => !!p)];
  return candidates.reduce((a, b) => (b.limits.aiRequestsPerUserPerDay > a.limits.aiRequestsPerUserPerDay ? b : a));
}

/**
 * Checks a usage limit from real records (never from a cached guess).
 * scope 'user': id is a user id (ai.requests.day, storage.bytes). The most generous plan
 * across the user's active organizations applies, or `opts.orgId` when given.
 * scope 'org': id is an organization id (org.members, job_postings.active, assessments.month, ai.requests.month).
 */
export async function checkLimit(scope: 'user' | 'org', id: string, metric: LimitMetric, opts: { orgId?: string | null } = {}): Promise<LimitCheck> {
  const result = (used: number, limit: number | null, period: string | null, explanation: string): LimitCheck => ({
    metric,
    scope,
    used,
    limit,
    allowed: limit === null || used < limit,
    period,
    explanation: limit === null ? `${explanation} No limit on this plan.` : `${explanation} Used ${used} of ${limit}.`,
  });

  if (scope === 'user') {
    const plan = opts.orgId ? await getPlan((await db.select({ p: organizations.planId }).from(organizations).where(eq(organizations.id, opts.orgId)))[0]?.p) : await bestPlanForUser(id);
    if (metric === 'ai.requests.day') {
      const [r] = await db
        .select({ n: sql<number>`count(*)::int` })
        .from(aiUsage)
        .where(and(eq(aiUsage.userId, id), gte(aiUsage.createdAt, startOfUtcDay()), inArray(aiUsage.status, ['ok', 'error', 'timeout'])));
      return result(r.n, plan.limits.aiRequestsPerUserPerDay, startOfUtcDay().toISOString().slice(0, 10), `${plan.name} plan: ${LIMIT_LABELS.aiRequestsPerUserPerDay.label.toLowerCase()}. ${LIMIT_LABELS.aiRequestsPerUserPerDay.explain}`);
    }
    if (metric === 'storage.bytes') {
      const [r] = await db
        .select({ n: sql<string>`coalesce(sum(${files.size}), 0)::bigint` })
        .from(files)
        .where(and(eq(files.ownerId, id), eq(files.status, 'ready'), ne(files.purpose, 'export')));
      const quota = Math.min(plan.limits.storagePerUserMb * 1024 * 1024, await getUserStorageQuotaBytes());
      return result(Number(r.n), quota, null, `Storage per user (bytes). ${LIMIT_LABELS.storagePerUserMb.explain}`);
    }
    throw new Error(`Metric ${metric} is not a user-scoped limit`);
  }

  const [o] = await db.select({ planId: organizations.planId, settings: organizations.settings }).from(organizations).where(eq(organizations.id, id));
  const plan = await getPlan(o?.planId);
  if (metric === 'org.members') {
    const [r] = await db.select({ n: sql<number>`count(*)::int` }).from(memberships).where(and(eq(memberships.orgId, id), eq(memberships.status, 'active')));
    return result(r.n, plan.limits.membersPerOrg, null, `${plan.name} plan: members per organization. ${LIMIT_LABELS.membersPerOrg.explain}`);
  }
  if (metric === 'job_postings.active') {
    const [r] = await db.select({ n: sql<number>`count(*)::int` }).from(jobPostings).where(and(eq(jobPostings.orgId, id), eq(jobPostings.status, 'published')));
    return result(r.n, plan.limits.activeJobPostings, null, `${plan.name} plan: active job postings. ${LIMIT_LABELS.activeJobPostings.explain}`);
  }
  if (metric === 'assessments.month') {
    const [r] = await db.select({ n: sql<number>`count(*)::int` }).from(assessments).where(and(eq(assessments.orgId, id), gte(assessments.createdAt, startOfUtcMonth())));
    return result(r.n, plan.limits.assessmentsPerMonth, startOfUtcMonth().toISOString().slice(0, 7), `${plan.name} plan: assessments per month. ${LIMIT_LABELS.assessmentsPerMonth.explain}`);
  }
  if (metric === 'ai.requests.month') {
    const policies = readOrgPolicies(o?.settings);
    const [r] = await db.select({ n: sql<number>`count(*)::int` }).from(aiUsage).where(and(eq(aiUsage.orgId, id), gte(aiUsage.createdAt, startOfUtcMonth())));
    return result(r.n, policies.aiMonthlyRequestLimit, startOfUtcMonth().toISOString().slice(0, 7), 'Organization policy: AI requests per month across all members.');
  }
  throw new Error(`Metric ${metric} is not an org-scoped limit`);
}

/** All org-scoped limits for an organization, for the admin usage view. */
export async function orgUsage(orgId: string) {
  return Promise.all((['org.members', 'job_postings.active', 'assessments.month', 'ai.requests.month'] as const).map((m) => checkLimit('org', orgId, m)));
}
